--6. Сколько времени проходит между первой и второй сессией 
--для менторов? А для менти?

with t1 as (
    select 
        mentor_id,
        session_date_time,
        row_number() over (partition by mentor_id order by session_date_time asc) as rn
    from 
        sessions
    where 
        mentor_id is not null
),
t2 as (
    select 
        a.mentor_id,
        (b.session_date_time::date - a.session_date_time::date) as days_between
    from 
        t1 a
    join 
        t1 b on a.mentor_id = b.mentor_id and b.rn = 2
    where 
        a.rn = 1
),
t3 as (
    select 
        mentee_id,
        session_date_time,
        row_number() over (partition by mentee_id order by session_date_time asc) as rn
    from 
        sessions
    where 
        mentee_id is not null
),
t4 as (
    select 
        a.mentee_id,
        (b.session_date_time::date - a.session_date_time::date) as days_between
    from 
        t3 a
    join 
        t3 b on a.mentee_id = b.mentee_id and b.rn = 2
    where 
        a.rn = 1
)
select 
    (select avg(days_between) from t2) as avg_days_mentor,
    (select percentile_cont(0.5) within group (order by days_between) from t2) as median_days_mentor,
    (select avg(days_between) from t4) as avg_days_mentee,
    (select percentile_cont(0.5) within group (order by days_between) from t4) as median_days_mentee;

--АНАЛИЗ
-- • Скорость возврата менторов относительно менти: Внутри своей роли менторы вовлекаются в повторную активность почти в два раза быстрее 
--учеников. Половина менторов (медиана) 
--проводят вторую встречу уже через 25.0 дней, в то время как половине менти (медиана) на повторный шаг требуется 46.0 дней (1.5 месяца).
-- • Сравнение типичного и затянутого сценариев: Среднее время возврата ментора (46.8 дня) практически совпадает с медианным временем 
--возврата ученика (46.0 дней). Это означает, что 
--сценарий, который для ментора является «затянутым» (с учетом редких встреч и долгих пауз), для обычного ученика является стандартной нормой.
-- • Влияние редких пользователей (выбросов): У менти среднее время возврата (74.6 дня, ~2.5 месяца) уходит далеко от медианы (46.0 дней). 
--Это указывает на наличие сильного «хвоста» из учеников, которые критически надолго пропадают 
--после первой сессии, утягивая средний показатель вверх. У менторов этот разрыв между средним (46.8) и медианой (25.0) выражен не так сильно.
