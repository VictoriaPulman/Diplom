--Задание 4*. Спрогнозируйте найм менторов. 
--
--Спрогнозируйте, сколько новых менторов нужно найти, если в следующем месяце количество активных менти увеличится на 500 человек.
--Учитывайте, что занятость новых менторов, будет такой же как у текущих. Объясните результат и ваше решение. 

with september_metrics as (
    -- Шаг 1: Собираем базовые показатели платформы за сентябрь 2022 года
    select 
        count(distinct mentee_id) as active_mentees,
        count(distinct mentor_id) as active_mentors,
        count(session_id) as total_sessions
    from 
        sessions
    where 
        session_status = 'finished'
        and date_trunc('month', session_date_time) = '2022-09-01'
),
load_and_demand as (
    -- Шаг 2: Считаем нагрузку ментора и будущий поток уроков от 500 новых менти
    select 
        -- Текущая еженедельная нагрузка на 1 ментора (по нашей прошлой SQL-логике)
        -- В сентябре 2022 года этот показатель равен ровно 0.502
        0.502 as mentor_weekly_load,
        
        -- Сколько еженедельных сессий принесут 500 новых менти: (500 * (Все сессии / 4.33)) / Все менти
        round(
            (500.0 * (total_sessions / 4.33)) / active_mentees, 
            2
        ) as additional_weekly_sessions
    from 
        september_metrics
)
-- Шаг 3: Вычисляем итоговый объем найма
select 
    additional_weekly_sessions,
    mentor_weekly_load,
    -- Делим гору сессий на нагрузку одного ментора и округляем в большую сторону
    ceil(additional_weekly_sessions / mentor_weekly_load) as required_new_mentors
from 
    load_and_demand;

