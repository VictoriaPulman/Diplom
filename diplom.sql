--8. Определите, в какой день недели последнего полного месяца прошло 
--больше всего встреч для каждого направления. 
--Определите самый загруженный день недели для каждого направления 
--менторства. В результатах выведите тип направления, день недели
--и количество встреч.


with domain_days_stat as (
    -- Шаг 1: Считаем количество сессий для каждого направления по дням недели
    select 
        d.name as domain_name,
        -- извлекаем номер дня недели (1 — понедельник, 7 — воскресенье)
        extract(isodow from s.session_date_time) as day_num,
        -- текстовое название дня недели для красоты
        to_char(s.session_date_time, 'TMDay') as day_name,
        count(s.session_id) as sessions_count
    from 
        sessions s
    join 
        domain d on s.mentor_domain_id = d.id
    where 
        date_trunc('month', s.session_date_time) = '2022-09-01'
    group by 
        d.name,
        extract(isodow from s.session_date_time),
        to_char(s.session_date_time, 'TMDay')
),
ranked_domain_days as (
    -- Шаг 2: Нумеруем дни недели внутри каждого направления от самых загруженных к менее
    select 
        domain_name,
        day_name,
        sessions_count,
        row_number() over (partition by domain_name order by sessions_count desc) as rn
    from 
        domain_days_stat
)
-- Шаг 3: Выводим только самые топовые (загруженные) дни для каждого направления
select 
    domain_name,
    day_name,
    sessions_count
from 
    ranked_domain_days
where 
    rn = 1
order by 
    sessions_count desc;

