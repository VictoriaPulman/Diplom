with geo_base as (
    -- Консолидация профилей пользователей со справочником географических наименований
    select 
        r.name as region_name,
        count(case when u.role = 'mentor' then 1 end) as mentors_count,
        count(case when u.role = 'mentee' then 1 end) as mentees_count,
        count(u.user_id) as total_users
    from 
        users u
    join 
        region r on u.region_id = r.id
    group by 
        r.name
)
-- Расчет процентных долей и относительной нагрузки на менторов по регионам
select 
    region_name,
    mentors_count,
    mentees_count,
    total_users,
    -- Доля пользователей региона от общего объема базы на платформе (%)
    round((total_users::numeric / sum(total_users) over()) * 100, 2) as region_share_pct,
    -- Среднее количество менти, приходящихся на одного ментора в рамках региона
    case 
        when mentors_count > 0 then round(mentees_count::numeric / mentors_count, 2)
        else 0 
    end as mentees_per_mentor
from 
    geo_base
order by 
    total_users desc;

